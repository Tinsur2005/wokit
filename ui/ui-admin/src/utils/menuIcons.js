// 系统原有菜单优先展示
const preferredIconNames = [
  'HomeFilled',
  'Calendar',
  'DocumentChecked',
  'Document',
  'FolderOpened',
  'Memo',
  'Timer',
  'AlarmClock',
  'User',
  'Avatar',
  'Key',
  'Lock',
  'Setting'
]

const preferredNames = new Set(preferredIconNames)
const allIconNames = Object.keys(ElementPlusIconsVue)

export const menuIconOptions = [
  ...preferredIconNames.map((name) => ({
    value: name,
    label: iconLabels[name] || name,
    component: ElementPlusIconsVue[name]
  })),
  ...allIconNames
    .filter((name) => !preferredNames.has(name))
    .sort((a, b) => a.localeCompare(b))
    .map((name) => ({
      value: name,
      label: iconLabels[name] || name,
      component: ElementPlusIconsVue[name]
    }))
]

export const menuIconMap = Object.fromEntries(
  menuIconOptions.map((item) => [item.value, item.component])
)
